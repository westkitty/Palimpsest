import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as T from 'three';
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js';
const glb=fs.readFileSync(new URL('../src/vnext/assets/palimpsest-f09-challenger.glb',import.meta.url));
const json=JSON.parse(glb.subarray(20,20+glb.readUInt32LE(12)));
const {scene,animations}=await new GLTFLoader().parseAsync(glb.buffer.slice(glb.byteOffset,glb.byteOffset+glb.byteLength),'');
const mixer=new T.AnimationMixer(scene);
const act=mixer.clipAction(animations[0]).setLoop(T.LoopOnce,1).play();act.paused=true;
const find=(s)=>scene.getObjectByName(s);
const pose=(f)=>{act.time=(f-1)/18;mixer.update(0);};
test('F09 package is reviewed F09.A only; true cut paper geometry, no foreign content',()=>{
  assert.equal(json.asset.extras.source_sha256,'22dc04b507e1720f0b269caeff3d02d9b2695e8149adbcd39bbefbd1b3674a14');
  assert.equal(json.meshes.length,74);
  assert.equal(json.cameras,undefined);
  assert.equal(json.images,undefined);
  assert.equal(json.extensions?.KHR_lights_punctual,undefined);
  assert.ok(!json.nodes.some(n=>/historical|history chart|caliper|schematic|testimony|reading desk|fabric bound case/i.test(n.name.replace(/Nonhistorical separation label/,''))));
  assert.equal(animations.length,1);
  assert.equal(animations[0].tracks.length,11);
  assert.equal(animations[0].name,'F09_A_Authored_Model_Star_Extraction');
  const hinges=animations[0].tracks.filter(x=>/F09_A_SPOKE_\d+.quaternion/.test(x.name));
  assert.equal(hinges.length,8);
  assert.ok(hinges.every(h=>find(h.name.split('.')[0]).children.length===3));
  assert.ok(find('F09_Dry_obsidian_model_mark').material instanceof T.MeshBasicMaterial);
});
test('F09 imported cyan fiber stretches, physically retracts, and holds with authored star folds',()=>{
  const spoke=find('F09_A_SPOKE_01'),pull=find('F09_A_PULL_RING'),filament=find('F09_A_FILAMENT');
  const effect=()=>filament.morphTargetInfluences.findIndex(v=>v>.98);
  assert.equal(filament.geometry.morphAttributes.position.length,44);
  pose(1);assert.equal(effect(),-1);assert.ok(Math.abs(pull.position.x+.96)<.0001);
  const first=spoke.quaternion.clone();assert.ok(find('F09_A_MATTE_ABSENCE').scale.x<.011);
  pose(28);const pulled=effect();assert.ok(pulled>=0);assert.ok(pull.position.x<-1.6);
  assert.ok(first.angleTo(spoke.quaternion)<.0001);
  pose(43);assert.ok(effect()>pulled);assert.ok(first.angleTo(spoke.quaternion)>.4);
  pose(70);const held=effect();assert.equal(held,43);assert.ok(first.angleTo(spoke.quaternion)>1.77);
  assert.ok(Math.abs(pull.position.x+2.60)<.0001);
  assert.ok(Math.abs(find('F09_A_MATTE_ABSENCE').scale.x-1)<.0001);
  pose(95);assert.equal(effect(),held);
});
