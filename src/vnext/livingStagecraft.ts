/**
 * One large, articulated skyline per mechanism, physically hinged behind
 * (never in front of) the source-authored scene. Seven distinct chapter
 * silhouettes are literal paper-cut profiles, not autogenerated galaxies.
 */
function makeSilhouette(profile:TheatreProfile, layer:number):THREE.Shape {
  const scale = 0.72 + layer * 0.10;
  const left=-3.48;
  const step=6.96/(profile.crest.length-1);
  const path=new THREE.Shape();
  path.moveTo(left,0);
  path.lineTo(left,profile.crest[0]*scale);
  profile.crest.forEach((height,i)=>{if(i>0)path.lineTo(left+i*step,height*scale);});
  path.lineTo(-left,0);
  path.closePath();
  if(layer===1 && profile.negativeSpace!=='none'){
    const hole=new THREE.Path();
    if(profile.negativeSpace==='orbit')hole.absellipse(0,0.89,0.33,0.28,0,Math.PI*2,true);
    else if(profile.negativeSpace==='glass')hole.absellipse(0,0.65,0.12,0.40,0,Math.PI*2,true);
    else hole.absellipse(0,0.90,0.34,0.34,0,Math.PI*2,true);
    path.holes.push(hole);
  }
  return path;
}
function brassBar(parent:THREE.Group,x:number,y:number,z:number,w:number,h:number,d:number,mat:THREE.Material):THREE.Mesh{
  const obj=new THREE.Mesh(new THREE.BoxGeometry(w,h,d),mat);
  obj.position.set(x,y,z);
  obj.castShadow=true;parent.add(obj);return obj;
}
function badgeTab(parent:THREE.Group,x:number,y:number,mat:THREE.Material):THREE.Mesh {
  const m=new THREE.Mesh(new THREE.BoxGeometry(0.24,0.05,0.075),mat);
  m.position.set(x,y,0.11);
  parent.add(m);
  return m;
}

/**
 * The page's own three documentary leaves rise as existing A/B/C are operated.
 * F05 B adds four source-bound material-processing markers; F09 A makes the
 * star-shaped paper emblem disappear in favour of a true dark void; F10 B
 * shows only the horizon's pitch-black streak, not a glowing orbital grid.
 * No green growth is created anywhere on F11's barren page.
 */
export class LivingStagecraft {
  public readonly root=new THREE.Group();
  public readonly profile:TheatreProfile;
  private readonly pivots:THREE.Group[]=[];
  private readonly progress=[0,0,0];
  private readonly targets=[0,0,0];
  private readonly manufacturingMarkers:THREE.Mesh[]=[];
  private modelStar:THREE.Mesh|null=null;
  private absentStar:THREE.Mesh|null=null;
  private blackHorizon:THREE.Mesh|null=null;

  constructor(public readonly folio:LaterFolioIndex) {
    this.profile=LIVING_THEATRE_PROFILES[folio];
    this.root.name='source-ink living theatrical relief';
    this.root.userData.editorialOnly=true;
    this.root.userData.sourceFolio='F'+String(folio+1).padStart(2,'0');
    this.root.userData.signature=this.profile.name;
    const brass=new THREE.MeshStandardMaterial({color:0xb49b6d,roughness:0.48,metalness:0.16,side:THREE.DoubleSide});
    const ink=new THREE.LineBasicMaterial({color:0x101622,transparent:true,opacity:0.94});
    const inkPaper=new THREE.MeshStandardMaterial({color:0x101622,roughness:0.94,metalness:0,side:THREE.DoubleSide});
    for(let i=0;i<3;i++){
      const pivot=new THREE.Group();
      pivot.name='mechanism '+SLOTS[i]+' die-cut page';
      pivot.position.set(0,0.32,-2.01-i*0.095);
      pivot.rotation.x=-0.7;
      const outline=makeSilhouette(this.profile,i);
      const geo=new THREE.ExtrudeGeometry(outline,{depth:0.038,bevelEnabled:false,steps:1,curveSegments:12});
      const paper=new THREE.Mesh(geo,new THREE.MeshStandardMaterial({
        color:this.profile.sheets[i],roughness:0.91,metalness:0.015,side:THREE.DoubleSide,flatShading:true,
      }));
      paper.receiveShadow=true;paper.castShadow=true;
      paper.name='distinct folio paper silhouette '+SLOTS[i];
      const edges=new THREE.LineSegments(new THREE.EdgesGeometry(geo,23),ink);
      edges.position.z=0.001;edges.name='separate dark ink cutting line';
      pivot.add(paper,edges);
      for(const side of [-1,1]){
        const support=brassBar(pivot,side*3.3,0.17,0.04,0.13,0.36,0.10,brass);
        support.rotation.x=-0.15;
        const rivet=new THREE.Mesh(new THREE.CylinderGeometry(0.06,0.06,0.10,8),brass);
        rivet.rotation.z=Math.PI/2;rivet.position.set(side*3.33,0.075,0);
        pivot.add(rivet);
      }
      // Two fine rules across the frontage make the die-cut an unmistakably
      // manufactured page, distinct from the literal objects behind it.
      for(const y of [0.12,0.19])brassBar(pivot,0,y,0.075,6.7,0.016,0.028,brass);
      this.root.add(pivot);this.pivots.push(pivot);
    }
    if(folio===4){
      // The four B steps describe harvest -> conversion -> extrusion -> ring.
      // Four separate mechanically raised marks, never a fabricated strain.
      for(let i=0;i<4;i++){
        const marker=badgeTab(this.pivots[1],-0.9+i*0.6,0.75,brass);
        marker.name='F05 documented manufacturing stage '+(i+1);
        marker.visible=false;
        this.manufacturingMarkers.push(marker);
      }
    }
    if(folio===8){
      const star=new THREE.Shape();
      for(let i=0;i<16;i++){
        const a=i*Math.PI/8;
        const r=i%2===0?0.32:0.16;
        const x=Math.cos(a)*r,y=1.15+Math.sin(a)*r;
        if(i===0)star.moveTo(x,y);else star.lineTo(x,y);
      }
      star.closePath();
      this.modelStar=new THREE.Mesh(new THREE.ShapeGeometry(star),new THREE.MeshStandardMaterial({
        color:0xe2c47c,roughness:0.9,side:THREE.DoubleSide,emissive:0x4e3516,emissiveIntensity:0.08,
      }));
      this.modelStar.name='F09 MODEL STAR paper emblem before extraction';
      this.modelStar.position.z=0.12;
      this.absentStar=new THREE.Mesh(new THREE.CircleGeometry(0.31,24),inkPaper);
      this.absentStar.name='F09 exact black absence after filament extraction';
      this.absentStar.position.set(0,1.15,0.13);
      this.absentStar.visible=false;
      this.pivots[0].add(this.modelStar,this.absentStar);
    }
    if(folio===9){
      this.blackHorizon=new THREE.Mesh(new THREE.BoxGeometry(6.6,0.11,0.04),inkPaper);
      this.blackHorizon.name='F10 inhabited-sky pure black streak; no luminous grid';
      this.blackHorizon.rotation.z=0.025;
      this.blackHorizon.position.set(0,0.72,0.12);
      this.blackHorizon.visible=false;
      this.pivots[1].add(this.blackHorizon);
    }
    this.root.traverse(obj=>{
      if(obj instanceof THREE.Mesh && obj.name.startsWith('F11'))obj.userData.noAdditionalLife=true;
    });
  }
  public sync(state:FolioRuntimeState):void {
    if(state.id!==this.folio)throw new RangeError('theatre assigned to wrong folio');
    SLOTS.forEach((slot,i)=>{
      const item=state.interactions[slot];
      const ratio=this.folio===4&&slot==='B'
        ? Math.min(1,item.step/4):item.active?1:0;
      this.targets[i]=ratio;
    });
    if(this.folio===4){
      for(let i=0;i<this.manufacturingMarkers.length;i++){
        this.manufacturingMarkers[i].visible=state.interactions.B.step>i;
      }
    }
    if(this.folio===8){
      const collapsed=state.interactions.A.active||state.interactions.A.locked;
      if(this.modelStar)this.modelStar.visible=!collapsed;
      if(this.absentStar)this.absentStar.visible=collapsed;
    }
    if(this.folio===9 && this.blackHorizon)
      this.blackHorizon.visible=state.interactions.B.active;
  }
  public update(dt:number,reducedMotion:boolean):void {
    for(let i=0;i<3;i++){
      const toward=this.targets[i];
      const alpha=reducedMotion?1:1-Math.exp(-5.2*Math.max(0,Math.min(0.06,dt)));
      this.progress[i]+=((toward-this.progress[i])*alpha);
      this.pivots[i].rotation.x=-0.70+this.progress[i]*0.72;
    }
  }
  /** Standalone geometry proof. The parent folio owns live scene disposal. */
  public dispose():void{
    const materials=new Set<THREE.Material>();
    const geometries=new Set<THREE.BufferGeometry>();
    this.root.traverse(obj=>{
      if(obj instanceof THREE.Mesh||obj instanceof THREE.LineSegments){
        geometries.add(obj.geometry);
        for(const mat of Array.isArray(obj.material)?obj.material:[obj.material])materials.add(mat);
      }
    });
    for(const g of geometries)g.dispose();
    for(const m of materials)m.dispose();
    this.root.clear();
  }
}
